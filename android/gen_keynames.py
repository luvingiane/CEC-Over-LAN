#!/usr/bin/env python3
"""Writes KeyNames.java: the Linux scan code -> KEY_* name table, from linux/input-event-codes.h.

Android hands the app the raw scan code of a key (KeyEvent.getScanCode()); the receiver's keymap
speaks the Linux names that `adb shell getevent -l` printed, so the app translates with this table.
Usage: gen_keynames.py <input-event-codes.h> <out.java>
"""
import re
import sys

DEFINE = re.compile(r"^#define\s+(KEY_[A-Z0-9_]+)\s+(0x[0-9a-fA-F]+|\d+)\s*(?:/\*.*)?$")


def table(header_text):
    """{code: name} for the plain numeric KEY_* defines; the first name of a code wins."""
    found = {}
    for line in header_text.splitlines():
        m = DEFINE.match(line.strip())
        if m:
            found.setdefault(int(m.group(2), 0), m.group(1))
    return found


def java(found):
    rows = ",\n".join(f'        {code}, "{name}"' for code, name in sorted(found.items()))
    return ("package org.cecoverlan.tv;\n\n// generated by gen_keynames.py, do not edit\n"
            "final class KeyNames {\n    private static final java.util.HashMap<Integer, String> T = new java.util.HashMap<>();\n"
            "    private static final Object[] DATA = {\n" + rows + "\n    };\n"
            "    static {\n        for (int i = 0; i < DATA.length; i += 2) T.put((Integer) DATA[i], (String) DATA[i + 1]);\n    }\n\n"
            "    static String of(int scanCode) { return T.get(scanCode); }\n}\n")


if __name__ == "__main__":
    src, dst = sys.argv[1:3]
    open(dst, "w").write(java(table(open(src).read())))
